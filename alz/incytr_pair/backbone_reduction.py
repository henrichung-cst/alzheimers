def _default_paths() -> tuple[str, str, str, str]:
    repo = str(_REPO_ROOT)
    wide_dir = os.path.join(repo, "outputs", "reports", "incytr_pair_mode", "wide")
    out_path = os.path.join(repo, "outputs", "reports", "incytr_pair_mode",
                            "backbone", "backbone_table.parquet")
    spec_path = os.path.join(repo, "outputs", "reports", "snrna_integration",
                             "song_expression_specificity.csv")
    counts_path = os.path.join(repo, "outputs", "reports", "snrna_integration",
                               "pseudobulk_cell_counts.csv")
    return wide_dir, out_path, spec_path, counts_path


def main(argv: list[str] | None = None) -> None:
    wide_dir_def, out_def, spec_def, counts_def = _default_paths()

    p = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("--wide-dir", default=wide_dir_def,
                   help="Directory containing *_incytr_output.parquet files "
                        f"(default: {wide_dir_def})")
    p.add_argument("--out", default=out_def,
                   help=f"Output parquet path (default: {out_def})")
    p.add_argument("--spec-path", default=spec_def,
                   help="Path to song_expression_specificity.csv "
                        f"(default: {spec_def})")
    p.add_argument("--counts-path", default=counts_def,
                   help="Path to pseudobulk_cell_counts.csv "
                        f"(default: {counts_def})")
    p.add_argument("--backbone-key", default="full",
                   choices=list(_KEY_COLS),
                   help="Path identity key: 'full' (default, locked 6-tuple), "
                        "'l-r-em', 'r-em-t', 'r-em' (for B4/B5 W1-gate analysis)")
    p.add_argument("--memory-limit", default="8GB",
                   help="DuckDB memory limit (default: 8GB)")
    p.add_argument("--verify", action="store_true",
                   help="Run sanity checks on the output after writing")
    p.add_argument("--quiet", action="store_true",
                   help="Suppress progress output")
    args = p.parse_args(argv)

    verbose = not args.quiet
    if verbose:
        print("=== backbone_reduction.py ===", flush=True)

    summary = reduce(
        wide_dir=args.wide_dir,
        out_path=args.out,
        backbone_key=args.backbone_key,
        spec_path=args.spec_path,
        counts_path=args.counts_path,
        memory_limit=args.memory_limit,
        verbose=verbose,
    )

    if verbose:
        print(f"\n  Summary:", flush=True)
        for k, v in summary.items():
            print(f"    {k}: {v}", flush=True)

    if args.verify:
        print("\n  Running verification...", flush=True)
        ok = verify(args.out, args.wide_dir, verbose=verbose)
        if not ok:
            print("\n  VERIFICATION FAILED", flush=True)
            sys.exit(1)
        print("\n  Verification passed.", flush=True)

    if verbose:
        print("\n=== done ===", flush=True)


if __name__ == "__main__":
    main()
